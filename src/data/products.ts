export function getOptimizedProductTitle(name: string, modelCode: string, categorySlug: string) {
  const suffixes: Record<string, string> = {
    weeders: "weeders",
    chainsaws: "chainsaws",
    "chaff-cutters": "chaff cutters",
    "wood-chippers": "wood chippers",
    harvesters: "crop harvesters",
    sprayers: "sprayers",
    "water-pumps": "water pumps",
    "earth-augers": "earth augers",
    "lawn-mowers": "lawn mowers",
    "tea-harvesters": "tea harvesters",
    "pressure-washers": "pressure washers",
    "rice-mills": "rice mills",
  };

  const suffix = suffixes[categorySlug] || "machines";
  
  const nameHas = name.toLowerCase().includes(suffix.toLowerCase()) || name.toLowerCase().includes(suffix.replace("s", "").toLowerCase());
  const modelHas = modelCode.toLowerCase().includes(suffix.toLowerCase()) || modelCode.toLowerCase().includes(suffix.replace("s", "").toLowerCase());
  
  const finalName = nameHas ? name : `${name} ${suffix}`;
  const finalModel = modelHas ? modelCode : `${modelCode} ${suffix}`;

  return {
    metaTitle: `X1 Power ${finalName} | Model: ${finalModel} — Bushra Impex`,
    h1Title: finalName,
    modelSub: finalModel,
  };
}

