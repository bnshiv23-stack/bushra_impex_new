export function getAccessoryImage(name: string, overrideMap?: Record<string, string>): string | undefined {
  if (overrideMap && overrideMap[name]) return overrideMap[name];
  const normalized = name.toLowerCase();
  const match = Object.entries(GLOBAL_ACCESSORY_IMAGES).find(([k]) => k.toLowerCase() === normalized);
  if (match) return match[1];
  // Fallback fuzzy matching
  if (normalized.includes('wheel') || normalized.includes('tyre')) return GLOBAL_ACCESSORY_IMAGES['Wheels'];
  if (normalized.includes('blade')) return GLOBAL_ACCESSORY_IMAGES['32 pcs Blade'];
  if (normalized.includes('fender')) return GLOBAL_ACCESSORY_IMAGES['Double Fender'];
  if (normalized.includes('disc')) return GLOBAL_ACCESSORY_IMAGES['Side-Disc'];
  return undefined;
}

